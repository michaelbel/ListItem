@Composable
fun BoarCard(
    entity: Boar,
    onClick: (Int) -> Unit,
    modifier: Modifier = Modifier
) {
    Card(
        modifier = modifier
            .fillMaxWidth()
            .wrapContentHeight(),
        shape = middleLargeIncreasedListItemShape
    ) {
        Column(
            modifier = Modifier
                .clickable { onClick(entity.id) }
                .fillMaxWidth()
        ) {
            Image(
                painter = painterResource(entity.drawableRes),
                contentDescription = null,
                contentScale = ContentScale.Crop,
                modifier = Modifier
                    .fillMaxWidth()
                    .aspectRatio(16F / 9F)
                    .clip(topLargeIncreasedListItemShape)
            )

            Text(
                text = entity.name,
                modifier = Modifier
                    .padding(horizontal = 16.dp, vertical = 12.dp)
                    .fillMaxWidth(),
                style = MaterialTheme.typography.bodyLarge.copy(color = MaterialTheme.colorScheme.onSurface, fontSize = 20.sp)
            )
        }
    }
}

